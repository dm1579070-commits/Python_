V = float(input("Скорость лодки в стоячей воде: "))
U = float(input("Скорость течения реки: "))
if U<V:
 T1=float(input("время движения лодки по озеру (ч): "))
 T2=float(input("время движения лодки пр.течения (ч): "))
 S=V*T1+(V-U)*T2
 print("Путь, пройденной лодкой: ", S)
else:
 print("Не соблюдены условия задачи")
